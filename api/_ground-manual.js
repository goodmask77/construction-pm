export function groundManualRecords() {
  return DAYS.map((d) => {
    // 品項段落：欄序同種子 [名稱,數量,佔比,套餐內,銷售額]；分析表無品項金額→記0
    const secs = d.cats.map(([cat, , items]) => ({
      title: cat, header: ["名稱", "數量", "佔比", "套餐內", "銷售額"],
      rows: items.map(([name, q, combo]) => [name, q, "", combo, 0]),
    })).filter((s) => s.rows.length)
    // 「總結」段＝總表分類帳（分類金額真值；前端 catAgg 有總結段就用它）；套餐不進總結（套餐段另計，避免重複）
    secs.push({ title: "總結", header: ["名稱", "數量", "佔比", "銷售額"], rows: d.cats.map(([cat, amt, items]) => [cat, items.reduce((t, it) => t + it[1], 0), "", amt]) })
    secs.push({ title: "套餐", header: ["名稱", "數量", "佔比", "套餐內", "銷售額"], rows: [["＋89 套餐", d.combos, "", d.combos, d.comboRev]] })
    return {
      id: "pos-" + d.date.replace(/-/g, "") + "manual-ground",
      date: d.date, period: d.date + "（喬亞POS報表手動回填）", store: "GROUN:D", subject: "GROUN:D 喬亞POS 營業總表回填",
      revenue: d.revenue, grossSales: d.gross, discount: d.discount,
      txCount: d.txCount, guests: 0, sales: d.revenue, serviceFee: 0, refund: d.refund,
      cash: d.cash, cashCount: null, card: d.card, cardCount: null, uber: 0, uberCount: null, posSales: 0, apiSales: 0,
      voidItems: 0, returnDish: d.refund, unsettled: 0, kv: {}, source: "manual-joya",
      partial: "喬亞POS總表人工回填：營收/單數/現金卡/退貨為總表真值；品項只有數量沒有金額（分類金額見總結段）",
      _details: { "總銷售額 (以類別分類)": secs },
    }
  })
}
